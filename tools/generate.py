"""Generate original garrison content from the project's balance contract."""
import argparse
from decimal import Decimal
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generated_files():
    config = json.loads((ROOT / 'balance.json').read_text())
    numeric = {k: v for k, v in config.items() if isinstance(v, (int, float))}
    constants = {f'gs_{k}': v for k, v in numeric.items()}
    step = Decimal(str(config['tier_step']))
    count = int(Decimal(str(config['maximum_penalty_relief'])) / step)
    tiers = [(i, step * i) for i in range(1, count + 1)]
    outputs = {}
    outputs['mod/common/script_values/gs_generated_parameters.txt'] = '# Generated by tools/generate.py; edit balance.json.\n' + ''.join(f'{k} = {v}\n' for k, v in constants.items())
    outputs['mod/common/static_modifiers/gs_generated_tiers.txt'] = '# Generated; one tier per state, no cumulative stacking.\n' + ''.join(f'gs_order_{i} = {{\n    state_turmoil_effects_mult = -{value}\n}}\n\n' for i, value in tiers)
    remove = ''.join(f'    remove_modifier = gs_order_{i}\n' for i, _ in tiers)
    apply = ''
    for n, (i, value) in enumerate(reversed(tiers)):
        apply += f'    {"if" if n == 0 else "else_if"} = {{\n        limit = {{ var:gs_relief >= {value} }}\n        add_modifier = {{ name = gs_order_{i} days = 45 }}\n    }}\n'
    outputs['mod/common/scripted_effects/gs_generated_tiers.txt'] = '# Generated; state scope.\ngs_clear_order = {\n' + remove + '}\n\ngs_apply_order = {\n' + apply + '}\n'
    jobs = config['jobs_per_level']
    officers = int(jobs * config['officer_share'])
    infra = config['infrastructure_per_level']
    icon = 'gfx/interface/icons/building_icons/building_barracks.dds'
    outputs['mod/common/buildings/gs_garrison_buildings.txt'] = f'''# Experimental fixed government facility; no deployable combat units.
building_gs_garrison = {{
    building_group = bg_government
    icon = "{icon}"
    required_construction = {config['construction_points_per_level']}
    production_method_groups = {{ pmg_gs_service }}
    ownership_type = no_ownership
    buildable = yes
    expandable = yes
    downsizeable = yes
    recruits_combat_units = no
    can_build_government = {{ always = yes }}
    can_build_private = {{ always = no }}
    ai_value = 0
}}
'''
    outputs['mod/common/production_method_groups/gs_garrison_groups.txt'] = f'''pmg_gs_service = {{
    production_methods = {{ pm_gs_active pm_gs_standby }}
    texture = "{icon}"
}}
'''
    outputs['mod/common/production_methods/gs_garrison_methods.txt'] = f'''# Jobs scale by level. Goods scale by actual staffing. Footprint is fixed.
pm_gs_active = {{
    texture = "{icon}"
    is_default = yes
    building_modifiers = {{
        level_scaled = {{
            building_employment_soldiers_add = {jobs - officers}
            building_employment_officers_add = {officers}
        }}
        workforce_scaled = {{
            goods_input_small_arms_add = {config['input_goods_per_level']['small_arms']}
            goods_input_grain_add = {config['input_goods_per_level']['grain']}
            goods_input_fabric_add = {config['input_goods_per_level']['fabric']}
            goods_input_paper_add = {config['input_goods_per_level']['paper']}
        }}
    }}
    state_modifiers = {{
        level_scaled = {{ state_infrastructure_add = -{infra} }}
    }}
}}

pm_gs_standby = {{
    texture = "{icon}"
    state_modifiers = {{
        level_scaled = {{ state_infrastructure_add = -{infra} }}
    }}
}}
'''
    for lang, texts in {
        'simp_chinese': ('卫戍营区', '卫戍勤务', '常备卫戍', '封存营区', '固定地方卫戍岗位，不生成野战部队。月度结算，军需短缺时停止治理收益。', '关闭岗位和治理收益，但保留基础设施占用。', '地方驻军维持秩序', '减少动乱惩罚；不代表动乱率立即下降。月度更新，连续服务后可产生有条件的长期政治态度变化。'),
        'english': ('Garrison Compound', 'Garrison Service', 'Standing Garrison', 'Mothballed Compound', 'Fixed local security employment; creates no field battalions. Benefits update monthly and stop during input shortages.', 'Closes jobs and governance benefits. The physical infrastructure footprint remains.', 'Local Garrison Order', 'Reduces penalties from turmoil, not the turmoil rate directly. Updated monthly; continuous service can enable conditional long-term political effects.')
    }.items():
        b, group, active, standby, desc, idle_desc, order, order_desc = texts
        entries = {'building_gs_garrison': b, 'building_gs_garrison_desc': desc, 'pmg_gs_service': group, 'pm_gs_active': active, 'pm_gs_active_desc': desc, 'pm_gs_standby': standby, 'pm_gs_standby_desc': idle_desc}
        for i, value in tiers:
            entries[f'gs_order_{i}'] = f'{order} ({value * 100:g}%)'
            entries[f'gs_order_{i}_desc'] = order_desc
        outputs[f'mod/localization/{lang}/gs_garrison_l_{lang}.yml'] = '\ufeffl_' + lang + ':\n' + ''.join(f' {key}:0 "{value}"\n' for key, value in entries.items())
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for name, content in generated_files().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_bytes() != content.encode('utf-8'):
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content.encode('utf-8'))
    if stale:
        raise SystemExit('Generated content is stale: ' + ', '.join(stale))
    print('Generated content ' + ('matches balance.json' if args.check else 'written'))

if __name__ == '__main__':
    main()
